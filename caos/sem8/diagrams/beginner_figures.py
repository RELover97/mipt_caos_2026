"""Precise beginner-friendly SVG teaching diagrams; run: python3 diagrams/beginner_figures.py.

Only uses Python stdlib + svgwrite. The text lives here so it can be audited
against the programs, unlike text generated by raster models.
"""
import os
import svgwrite
from xml.sax.saxutils import escape

OUT=os.path.dirname(os.path.abspath(__file__))
NAVY='#10243B'; BLUE='#2364C8'; SKY='#EAF3FF'; TEAL='#087D6B'; MINT='#E7F6F0'; AMBER='#A96B08'; CREAM='#FFF3D7'; RED='#BC4145'; ROSE='#FFE9EB'; BG='#F7F9FD'; LINE='#D9E2EF'; GRAY='#56677D'; PURPLE='#6F48BC'; LAV='#F2EDFC'; WHITE='#FFFFFF'

class Fig:
 def __init__(self,name,title,subtitle,h=640):
  self.w=1280; self.h=h
  self.d=svgwrite.Drawing(os.path.join(OUT,name+'.svg'),size=(f'{self.w}px',f'{self.h}px'),viewBox=f'0 0 {self.w} {self.h}',profile='full')
  self.r(0,0,1280,h,BG,rx=0,stroke=None)
  self.r(0,0,1280,84,NAVY,rx=0,stroke=None)
  self.t(40,37,title,30,WHITE,bold=True)
  self.t(40,67,subtitle,16,'#C9D8EF')
 def r(self,x,y,w,h,fill=WHITE,rx=17,stroke=LINE,sw=1.5):
  self.d.add(self.d.rect(insert=(x,y),size=(w,h),rx=rx,ry=rx,fill=fill,stroke=stroke or 'none',stroke_width=sw))
 def t(self,x,y,s,size=20,color=NAVY,bold=False,anchor='start'):
  self.d.add(self.d.text(s,insert=(x,y),font_family='DejaVu Sans, Arial, sans-serif',font_size=size,font_weight=('700' if bold else '400'),fill=color,text_anchor=anchor))
 def lines(self,x,y,arr,size=18,color=GRAY,dy=27,bold=False):
  for j,s in enumerate(arr): self.t(x,y+j*dy,s,size,color,bold)
 def ln(self,x1,y1,x2,y2,color=LINE,sw=3,dashed=False):
  args={'stroke':color,'stroke_width':sw,'stroke_linecap':'round'}
  if dashed: args['stroke_dasharray']='6,8'
  self.d.add(self.d.line((x1,y1),(x2,y2),**args))
 def arr(self,x1,y1,x2,y2,color=BLUE,sw=3,head=11):
  self.ln(x1,y1,x2,y2,color,sw)
  import math
  a=math.atan2(y2-y1,x2-x1)
  p1=(x2-head*math.cos(a-0.5),y2-head*math.sin(a-0.5)); p2=(x2-head*math.cos(a+0.5),y2-head*math.sin(a+0.5))
  self.d.add(self.d.polygon([(x2,y2),p1,p2],fill=color))
 def badge(self,x,y,label,fg=BLUE,bg=SKY,w=None):
  w=w or max(68,18+len(label)*11)
  self.r(x,y-25,w,36,bg,10,None)
  self.t(x+12,y,label,16,fg,True)
 def box(self,x,y,w,h,head,body=None,fill=WHITE,accent=BLUE):
  self.r(x,y,w,h,fill)
  self.r(x,y,7,h,accent,rx=3,stroke=None)
  self.t(x+24,y+38,head,21,NAVY,True)
  if body: self.lines(x+24,y+70,body,17,GRAY,25)
 def panel(self,x,y,w,h,num,title,sub=None,accent=BLUE):
  self.r(x,y,w,h,WHITE)
  self.r(x+18,y+18,42,42,accent,12,None)
  self.t(x+39,y+47,str(num),21,WHITE,True,'middle')
  self.t(x+75,y+45,title,20,NAVY,True)
  if sub: self.t(x+24,y+84,sub,16,GRAY)
 def hr(self,y): self.ln(38,y,1242,y,LINE,2)
 def foot(self,text):
  self.r(34,self.h-61,1212,40,'#ECF1F8',8,None)
  self.t(52,self.h-35,text,17,GRAY)
 def save(self): self.d.save()

